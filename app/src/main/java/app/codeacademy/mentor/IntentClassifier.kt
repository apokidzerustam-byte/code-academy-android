package app.codeacademy.mentor

/**
 * Намерение по тексту запроса: правила на основах слов (русский и английский).
 * Просьба о решении проверяется первой: она перекрывает «объясни», «проверь» и т. п.,
 * если в одном запросе есть и то и другое («объясни и дай готовый код»).
 */
object IntentClassifier {
    private fun norm(s: String) = s.lowercase().replace('ё', 'е').replace(Regex("\\s+"), " ")

    private val SOLUTION = listOf(
        Regex("(дай|скинь|покажи|напиши|выведи|пришли|отправь|выдай|верни|распечатай|сгенерируй|продиктуй|дайте|напишите|покажите|показать|написать|дать|выдать|вывести|прислать|скинуть)\\S*\\s+(мне\\s+)?(\\S+\\s+){0,3}(решени|ответ|готов|код|программ|вариант|скрипт|функци|запрос|верстк|разметк)"),
        Regex("(реши|решите|сделай|сделайте|выполни|допиши|дополни|продолжи|закончи|заверши|исправь|исправьте|почини|перепиши)\\S*\\s+(\\S+\\s+){0,3}(за меня|задани|задач|целиком|полностью|до конца|весь|всю|все|код|программ)"),
        Regex("(готов\\S*|полн\\S*|правильн\\S*|верн\\S*|итогов\\S*|финальн\\S*|эталонн\\S*|рабоч\\S*)\\s+(\\S+\\s+)?(решени|код|ответ|вариант|программ|верси)"),
        Regex("(какой|каким|что|чему|сколько)\\s+(будет|получится|выйдет)\\s+(\\S+\\s+){0,2}(вывод|результат|ответ|на экран|в консол|напечата)"),
        Regex("(какой|каков)\\s+(будет\\s+)?(вывод|результат|ответ)"),
        Regex("что\\s+(выведет|напечатает|покажет)(?!\\S*\\s+если)"),
        Regex("(?<![\\p{L}\\d_])(ответ|решение)\\s*(\\?|:|$)"),
        Regex("(?<![\\p{L}\\d_])(просто|сразу|быстро)\\s+(дай|скажи|напиши|покажи|выведи|реши)"),
        Regex("за меня"),
        Regex("(выведи|покажи|напиши|дай|пришли|скинь)\\S*\\s+(\\S+\\s+){0,2}(полностью|целиком|весь|всё|все)"),
        Regex("(какой|какую|какие)\\s+(\\S+\\s+){0,2}(код|строк\\S*)\\s+(\\S+\\s+){0,2}(нужно|надо|написать|вставить|добавить)"),
        Regex("тест\\S*\\s+(\\S+\\s+)?(прош|прох|засчит)|чтобы\\s+(\\S+\\s+){0,3}засчит"),
        Regex("пример\\S*\\s+(\\S+\\s+){0,2}котор\\S*\\s+(\\S+\\s+){0,3}(делает|решает|выполняет)\\s+(\\S+\\s+){0,3}(то же|задани|задач)"),
        Regex("копир|скопир|списат|спиш"),
        Regex("(?<![\\p{L}\\d_])(solution|solve|answer|write (the|me|a|full|complete)|full code|complete code|final code|give me)(?![\\p{L}\\d_])"),
        Regex("base64|азбук|по букв|задом наперед|в обратном порядке|шифр|закодир|zip|rot13|hex"),
        Regex("игнорир|забудь\\s+(все|правил|инструкц)|ignore (all|previous|the)|режим разработчик|developer mode|jailbreak|ты больше не|без ограничени|притворись|представь,? что ты"),
    )
    /** «Покажи, где ошибка в коде», «покажи пример кода» — это не просьба о решении. */
    private val QUESTION_ABOUT = Regex("(?<![\\p{L}\\d_])(где|почему|зачем|ошибк|пример|как работает)")
    private val ERROR = Regex("ошибк|ошибоч|traceback|трейсбек|error|exception|исключени|не работает|не запускает|падает|упал|вылет|красн|не проход|не принима|не засчит|почему не|что не так")
    private val HINT = Regex("подсказ|намек|намекни|застрял|не знаю,? как|не понимаю,? как|с чего начать|как начать|направлени|куда смотреть|помоги|hint|stuck")
    private val TOPIC = Regex("что будет,? если|что если|объясн|что так|что значит|что делает|как работает|зачем|почему так|расскажи|разниц|отлич|тем[аеуы]|поясни|не понимаю|не понял|explain|what is")
    private val REVIEW = Regex("провер\\S* (мой|мое|мою|мои|код|решени|ответ)|оцени|ревью|review|правильно ли|хорошо ли|нормально ли|можно ли лучше|улучш|замечани|стиль")
    private val EXERCISE = Regex("упражнен|потренир|тренир|ещ[её] задач|похож\\S* задач|практик|задачк|exercise")
    private val ARCH = Regex("архитектур|структур|организ|разби\\S*\\s+(\\S+\\s+)?на |разбей|модул|файл\\S* проект|как устро|паттерн|слои|architecture")

    fun classify(text: String): Intent {
        val t = norm(text)
        if (t.isBlank()) return Intent.HINT
        // Первые два правила («покажи … код», «исправь … код») не срабатывают на «покажи, где ошибка в коде».
        if (SOLUTION.withIndex().any { (i, re) -> re.findAll(t).any { i >= 2 || !QUESTION_ABOUT.containsMatchIn(it.value) } }) {
            return Intent.SOLUTION_REQUEST
        }
        return when {
            ERROR.containsMatchIn(t) -> Intent.EXPLAIN_ERROR
            REVIEW.containsMatchIn(t) -> Intent.REVIEW
            EXERCISE.containsMatchIn(t) -> Intent.EXERCISE
            ARCH.containsMatchIn(t) -> Intent.ARCHITECTURE
            HINT.containsMatchIn(t) -> Intent.HINT
            TOPIC.containsMatchIn(t) -> Intent.EXPLAIN_TOPIC
            else -> Intent.OTHER
        }
    }
}
