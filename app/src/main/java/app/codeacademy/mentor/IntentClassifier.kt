package app.codeacademy.mentor

/**
 * Намерение по тексту запроса: правила на основах слов (русский и английский).
 * Просьба о решении проверяется первой: она перекрывает «объясни», «проверь» и т. п.,
 * если в одном запросе есть и то и другое («объясни и дай готовый код»).
 */
object IntentClassifier {
    private fun norm(s: String) = s.lowercase().replace('ё', 'е').replace(Regex("\\s+"), " ")

    /** guarded — не срабатывает в вопросах «как/почему/где/что такое…»; answerOnly — только в заданиях «предскажи». */
    private class Rule(pattern: String, val guarded: Boolean = false, val answerOnly: Boolean = false) {
        val re = Regex(pattern)
    }

    private val SOLUTION = listOf(
        Rule("(дай|скинь|покажи|напиши|выведи|пришли|отправь|выдай|верни|распечатай|сгенерируй|продиктуй|дайте|напишите|покажите|показать|написать|дать|выдать|вывести|прислать|скинуть)\\S*\\s+(мне\\s+)?(\\S+\\s+){0,3}(решени|ответ|готов|код|программ|вариант|скрипт|функци|запрос|верстк|разметк)", guarded = true),
        Rule("(реши|решите|сделай|сделайте|выполни|допиши|дополни|продолжи|закончи|заверши|исправь|исправьте|почини|перепиши)\\S*\\s+(\\S+\\s+){0,3}(за меня|задани|задач|целиком|полностью|до конца|весь|всю|все|код|программ)", guarded = true),
        Rule("(готов\\S*|полн\\S*|правильн\\S*|верн\\S*|итогов\\S*|финальн\\S*|эталонн\\S*|рабоч\\S*)\\s+(\\S+\\s+)?(решени|код|ответ|вариант|программ|верси)"),
        Rule("(какой|каким|что|чему|сколько)\\s+(будет|получится|выйдет)\\s+(\\S+\\s+){0,2}(вывод|результат|ответ|на экран|в консол|напечата)", answerOnly = true),
        Rule("(какой|каков)\\s+(будет\\s+)?(вывод|результат|ответ)", answerOnly = true),
        Rule("что\\s+(выведет|напечатает|покажет)(?!\\S*\\s+если)", answerOnly = true),
        Rule("(?<![\\p{L}\\d_])(ответ|решение)\\s*(\\?|:|$)"),
        Rule("(?<![\\p{L}\\d_])(просто|сразу|быстро)\\s+(дай|скажи|напиши|покажи|выведи|реши)"),
        Rule("за меня"),
        Rule("(выведи|покажи|напиши|дай|пришли|скинь)\\S*\\s+(\\S+\\s+){0,2}(полностью|целиком|весь|всё|все)", guarded = true),
        Rule("(какой|какую|какие)\\s+(\\S+\\s+){0,2}(код|строк\\S*)\\s+(\\S+\\s+){0,2}(нужно|надо)\\s+(\\S+\\s+){0,3}(чтобы|тест|засчит|задани)"),
        Rule("чтобы\\s+(\\S+\\s+){0,3}(тест\\S*\\s+(\\S+\\s+)?(прош|прох)|засчит)"),
        Rule("пример\\S*\\s+(\\S+\\s+){0,2}котор\\S*\\s+(\\S+\\s+){0,3}(делает|решает|выполняет)\\s+(\\S+\\s+){0,3}(то же|задани|задач)"),
        Rule("(скопир|списа|спиш)\\S*\\s+(\\S+\\s+){0,2}(решени|код|ответ|у тебя)", guarded = true),
        Rule("(?<![\\p{L}\\d_])(solution|solve|answer|write (the|me|a|full|complete)|full code|complete code|final code|give me)(?![\\p{L}\\d_])"),
        Rule("base64|азбук|по букв|задом наперед|rot13|(зашифр|закодир)\\S*\\s+(\\S+\\s+){0,2}(решени|код|ответ)"),
        Rule("игнорир|забудь\\s+(все|правил|инструкц)|ignore (all|previous|the)|режим разработчик|developer mode|jailbreak|ты больше не|без ограничени|притворись|представь,? что ты"),
    )
    /** Вопрос о теме, а не просьба о решении: «как написать функцию?», «покажи, где ошибка». */
    private val QUESTION_ABOUT = Regex("(?<![\\p{L}\\d_])(как|где|почему|зачем|что такое|объясни|пример|ошибк\\S*|как работает)(?![\\p{L}\\d_])")
    private val ERROR = Regex("ошибк|ошибоч|traceback|трейсбек|error|exception|исключени|не работает|не запускает|падает|упал|вылет|красн|не проход|не принима|не засчит|почему не|что не так")
    private val HINT = Regex("подсказ|намек|намекни|застрял|не знаю,? как|не понимаю,? как|с чего начать|как начать|направлени|куда смотреть|помоги|hint|stuck")
    private val TOPIC = Regex("что будет,? если|что если|объясн|что так|что значит|что делает|как работает|зачем|почему так|расскажи|разниц|отлич|тем[аеуы]|поясни|не понимаю|не понял|explain|what is")
    private val REVIEW = Regex("провер\\S* (мой|мое|мою|мои|код|решени|ответ)|оцени|ревью|review|правильно ли|хорошо ли|нормально ли|можно ли лучше|улучш|замечани|стиль")
    private val EXERCISE = Regex("упражнен|потренир|тренир|ещ[её]\\s+(\\S+\\s+)?задач|похож\\S* задач|практик|задачк|exercise")
    private val ARCH = Regex("архитектур|структур|организ|разби\\S*\\s+(\\S+\\s+)?на |разбей|модул|файл\\S* проект|как устро|паттерн|слои|architecture")

    /**
     * @param answerTask задание «предскажи результат»: там вопрос «что выведет программа?» — просьба об ответе,
     *   а в остальных случаях — обычный вопрос о теме.
     */
    fun classify(text: String, answerTask: Boolean = true): Intent {
        val t = norm(text)
        if (t.isBlank()) return Intent.HINT
        val question = QUESTION_ABOUT.containsMatchIn(t)
        if (SOLUTION.any { r -> (!r.guarded || !question) && (!r.answerOnly || answerTask) && r.re.containsMatchIn(t) }) {
            return Intent.SOLUTION_REQUEST
        }
        return when {
            ERROR.containsMatchIn(t) -> Intent.EXPLAIN_ERROR
            REVIEW.containsMatchIn(t) -> Intent.REVIEW
            EXERCISE.containsMatchIn(t) -> Intent.EXERCISE
            ARCH.containsMatchIn(t) -> Intent.ARCHITECTURE
            HINT.containsMatchIn(t) -> Intent.HINT
            TOPIC.containsMatchIn(t) -> Intent.EXPLAIN_TOPIC
            else -> Intent.OTHER
        }
    }
}
