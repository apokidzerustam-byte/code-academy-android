notes = """
# Списки

**Список** — упорядоченный набор значений в квадратных скобках.

```python
items = ["хлеб", "молоко", "сыр"]
print(items[0])     # хлеб
print(items[-1])    # сыр
print(len(items))   # 3
```

## Изменение и добавление

```python
items = ["хлеб", "молоко", "сыр"]
items[1] = "кефир"          # заменить элемент
items.append("яблоки")      # добавить в конец
print(items)                # ['хлеб', 'кефир', 'сыр', 'яблоки']
```

## Перебор

```python
for item in ["хлеб", "кефир", "сыр"]:
    print("-", item)
```

## Числовые списки

```python
marks = [5, 4, 3, 5, 4]
print(sum(marks), min(marks), max(marks))   # 21 3 5
print(sum(marks) / len(marks))              # 4.2 — среднее
```

## Список из ввода

```python
nums = []
for x in ["2", "7", "1"]:     # в программе здесь будет input()
    nums.append(int(x))
print(nums)                   # [2, 7, 1]
```

| Функция / метод | Что делает |
| --- | --- |
| `len(lst)` | количество элементов |
| `lst.append(x)` | добавить `x` в конец |
| `sum`, `min`, `max` | сумма, минимум, максимум |

`lst[len(lst)]` → `IndexError: list index out of range`.

## Запомните

1. Индексы с нуля, `-1` — последний элемент.
2. Пустой список — `[]`, наполняем через `append`.
3. Списки можно менять, строки — нет.
"""

