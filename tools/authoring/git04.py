notes = """
# Конфликты слияния

```bash
git merge feature            # CONFLICT (content): ...
git status -s                # UU greeting.txt
cat greeting.txt             # метки <<<<<<<, =======, >>>>>>>
# правим файл: оставляем нужное, метки убираем
git add greeting.txt
git commit --no-edit
git merge --abort            # передумали — вернуть всё как было
```

## Метки

```text
<<<<<<< HEAD
вариант из текущей ветки
=======
вариант из сливаемой ветки
>>>>>>> feature
```

## Запомните

1. Конфликт — это нормально, данные не потеряны.
2. Метки нужно удалить из файла полностью.
3. После правки: `git add`, затем `git commit`.
"""

