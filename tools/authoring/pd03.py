from lib import *

def review_task(id, title, code, statement, wrong, hints_, explanation):
    answer = run_out(code)
    for w, why in wrong:
        assert w.strip() != answer.strip(), (id, "неверный ответ совпал с верным", why)
    return asg(id, "review", title, statement, title, "Нет.", "Вывод программы.", ["Ответьте без запуска кода."], hints_,
               {"kind": "answer", "expected_answer": answer}, answer, explanation, ["Все строки вывода верны."], wrong, code=code)


