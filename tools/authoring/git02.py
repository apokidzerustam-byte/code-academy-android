notes = """
# Изменения и отмена

```bash
git diff                   # рабочая папка и индекс
git diff --staged          # индекс и последний коммит
git diff --stat            # краткая сводка
git restore --staged file  # убрать из индекса (правки останутся)
git restore file           # отбросить несохранённые правки
git revert --no-edit HEAD  # отменить последний коммит новым коммитом
```

| Хочу… | Команда |
|---|---|
| посмотреть правки | `git diff` |
| посмотреть, что войдёт в коммит | `git diff --staged` |
| вернуть файл из индекса | `git restore --staged файл` |
| отбросить правки (необратимо!) | `git restore файл` |
| отменить сохранённый коммит | `git revert --no-edit HEAD` |

## Запомните

1. Три области: рабочая папка, индекс, история.
2. `git restore файл` нельзя отменить — несохранённое пропадёт.
3. `git revert` не переписывает историю — безопасен для общих репозиториев.
"""

