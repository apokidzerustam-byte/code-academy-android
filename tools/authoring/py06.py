notes = """
# Условия: if, elif, else

## Сравнения

| Запись | Значение |
| --- | --- |
| `a > b`, `a < b` | больше, меньше |
| `a >= b`, `a <= b` | больше или равно, меньше или равно |
| `a == b` | равно |
| `a != b` | не равно |

Результат сравнения — `True` (истина) или `False` (ложь).

## if, else, elif

```python
score = 75
if score >= 90:
    print("отлично")
elif score >= 70:
    print("хорошо")        # выполнится эта ветка
else:
    print("нужно повторить")
```

- После условия — **двоеточие**.
- Команды ветки — с **отступом** 4 пробела.
- Выполняется первая подходящая ветка; `else` — если не подошла ни одна.

## Чётность

```python
n = 7
if n % 2 == 0:
    print("чётное")
else:
    print("нечётное")
```

## Если появилась ошибка

| Сообщение | Причина |
| --- | --- |
| `IndentationError` | нет отступа после двоеточия или отступы разной ширины |
| `SyntaxError` в `if x = 5:` | в условии нужен `==` |

## Запомните

1. `=` присваивает, `==` сравнивает.
2. Двоеточие и отступ обязательны.
3. Порядок условий в `elif` важен: проверяются сверху вниз.
"""

