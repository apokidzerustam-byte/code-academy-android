notes = """
# Цикл while

`while` повторяет команды блока, **пока** условие истинно.

```python
i = 1
while i <= 5:
    print(i)
    i += 1        # то же, что i = i + 1
```

## Накопление

```python
total = 0
i = 1
while i <= 100:
    total += i
    i += 1
print(total)      # 5050 — вывод после цикла, без отступа
```

## break

```python
n = 0
while True:
    n += 1
    if n == 3:
        break     # немедленный выход из цикла
print(n)          # 3
```

## Бесконечный цикл

Если в цикле не меняется переменная из условия, цикл не закончится. Нажмите **Стоп** и проверьте счётчик.

| Запись | То же самое |
| --- | --- |
| `x += 1` | `x = x + 1` |
| `x -= 2` | `x = x - 2` |
| `x *= 3` | `x = x * 3` |

## Запомните

1. Условие проверяется перед каждой итерацией.
2. Меняйте счётчик внутри цикла.
3. Результат накопления выводите после цикла.
"""

